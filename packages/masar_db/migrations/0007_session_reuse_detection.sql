-- 0007) كشف إعادة استخدام رمز التحديث — إغلاق ثغرة حقيقية
--
-- كان التدوير يستبدل ``refresh_token_hash`` في مكانه، فلا يبقى للرمز القديم
-- أثر في الجدول. أثر ذلك أن فرع «كشف إعادة الاستخدام» كان **غير قابل للوصول
-- إطلاقًا**: إعادة إرسال رمز مُدوَّر تُقابَل بـ«رمز غير صالح» عامة، لا بإبطال
-- الجلسات.
--
-- لماذا هذا مهم: رمز تحديث مسروق يُستخدم مرة واحدة فيحصل المهاجم على جلسة
-- حية. حين يحاول المستخدم الشرعي التحديث برمزه (الذي صار قديمًا) يفشل بصمت
-- ويعيد الدخول — بينما تبقى جلسة المهاجم عاملة. الكشف الصحيح يقلب المعادلة:
-- أول إعادة استخدام تُبطل **كل** جلسات المستخدم، فيخسر الطرفان الجلسة ويعيد
-- المستخدم الشرعي الدخول بينما يخرج المهاجم.
-- ============================================================================

ALTER TABLE user_sessions
    ADD COLUMN IF NOT EXISTS previous_token_hash text;

COMMENT ON COLUMN user_sessions.previous_token_hash IS
    'تجزئة الرمز السابق مباشرةً — وجودها هو ما يجعل إعادة الاستخدام قابلة للكشف';

CREATE INDEX IF NOT EXISTS user_sessions_previous_token_idx
    ON user_sessions (previous_token_hash)
    WHERE previous_token_hash IS NOT NULL;

ALTER TABLE user_sessions
    ADD COLUMN IF NOT EXISTS rotation_count integer NOT NULL DEFAULT 0;

COMMENT ON COLUMN user_sessions.rotation_count IS
    'عدد مرات تدوير رمز التحديث — مؤشر تشغيلي على عمر الجلسة ونشاطها';
